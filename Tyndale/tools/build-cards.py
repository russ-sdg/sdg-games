#!/usr/bin/env python3
"""Build the Tyndale card gallery data.

  python3 Tyndale/tools/build-cards.py          (run from the repo root)

Converts the card scans in assets/ (Tyndale*Card*.png, 820x1120) to WebP at 480 and 820 px wide in
assets/tyndale/cards/, and writes Tyndale/cards-data.js for the product page gallery (window.SDG_CARDS).
Also writes the board, scorecard and photos used on the page to assets/tyndale/.
"""
import json, os
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
A = os.path.join(ROOT, 'assets')
OUT = os.path.join(A, 'tyndale')
CARDS = os.path.join(OUT, 'cards')
DATA = os.path.join(ROOT, 'Tyndale', 'cards-data.js')
WIDTHS = (480, 820)

GROUPS = [
    ('tyndale', 'Tyndale', 'The player on the run'),
    ('agents', "Bishop's Agents", 'Who is searching for him'),
    ('location', 'Location cards', 'Is he here?'),
    ('bible', 'Bible cards', 'What has he left behind?'),
]
# (id, group, name, source file)
CARDS_LIST = [
    ('tyndale-back', 'tyndale', 'Tyndale card back', 'TyndaleCardBack.png'),
    ('tyndale', 'tyndale', 'William Tyndale', 'TyndaleTyndaleCard.png'),
    ('agents-back', 'agents', "Bishop's Agent card back", 'TyndaleBishopsBack.png'),
    ('vaughn', 'agents', 'Stephen Vaughn', 'TyndaleVaughnCard.png'),
    ('holt', 'agents', 'William Holt', 'TyndaleHoltCard.png'),
    ('dobneck', 'agents', 'John Dobneck', 'TyndaleDobneckCard.png'),
    ('stokesley', 'agents', 'John Stokesley', 'TyndaleStokesleyCard.png'),
    ('more', 'agents', 'Thomas More', 'TyndaleMoreCard.png'),
    ('phillips', 'agents', 'Henry Phillips', 'TyndalePhillipsCard.png'),
    ('location-back', 'location', 'Location card back', 'TyndaleHereCardBack.png'),
    ('here', 'location', 'Here', 'TyndaleHereCard.png'),
    ('not-here', 'location', 'Not here', 'TyndaleNotHereCard.png'),
    ('near', 'location', 'Near', 'TyndaleNearCard.png'),
    ('far', 'location', 'Far', 'TyndaleFarCard.png'),
    ('bible-back', 'bible', 'Bible card back', 'TyndaleBibleBack.png'),
    ('nothing', 'bible', 'Nothing to report', 'TyndaleNothingCard.png'),
    ('rumors', 'bible', 'Rumors of a translation', 'TyndaleRumorsCard.png'),
    ('new-testament', 'bible', 'New Testament', 'TyndaleNewTestamentCard.png'),
    ('pentateuch', 'bible', 'Pentateuch', 'TyndalePentateuchCard.png'),
    ('historical', 'bible', 'Historical Books', 'TyndaleHistoricalCard.png'),
    ('old-testament', 'bible', 'Old Testament', 'TyndaleOldTestamentCard.png'),
]
# Pictures used on the page: (output name, source, max width)
PICTURES = [('board', 'TyndaleBoard.png', 800), ('scorecard', 'TyndaleScorecard.webp', 800), ('glimpse', 'Tyndale_glimpse.png', 400),
            ('example-tyndale', 'TyndaleExample.png', 884), ('example-agent', 'BishopsAgentsExample.png', 884), ('pawns', 'TyndalePawns.png', 100), ('die', 'TyndaleDie.png', 60)]

def newer(dst, src):
    return os.path.exists(dst) and os.path.getmtime(dst) >= os.path.getmtime(src)

def main():
    os.makedirs(CARDS, exist_ok=True)
    cards, wanted = [], set()
    for cid, group, name, f in CARDS_LIST:
        src = os.path.join(A, f)
        im = None
        for w in WIDTHS:
            out = f'{cid}-{w}.webp'
            wanted.add(out)
            dst = os.path.join(CARDS, out)
            if newer(dst, src):
                continue
            im = im or Image.open(src).convert('RGBA')
            t = im if w >= im.width else im.resize((w, round(w * im.height / im.width)), Image.LANCZOS)
            t.save(dst, quality=86, method=6)
        probe = Image.open(os.path.join(CARDS, f'{cid}-{WIDTHS[-1]}.webp'))
        cards.append({'id': cid, 'group': group, 'name': name, 'src': f'../assets/tyndale/cards/{cid}', 'widths': list(WIDTHS), 'w': probe.width, 'h': probe.height})
    for f in os.listdir(CARDS):
        if f.endswith('.webp') and f not in wanted:
            os.remove(os.path.join(CARDS, f))
    for name, f, maxw in PICTURES:
        src = os.path.join(A, f); dst = os.path.join(OUT, name + '.webp')
        if newer(dst, src):
            continue
        im = Image.open(src).convert('RGBA' if name in ('pawns', 'die') else 'RGB')
        if im.width > maxw:
            im = im.resize((maxw, round(maxw * im.height / im.width)), Image.LANCZOS)
        im.save(dst, quality=86, method=6)
    data = {'total': len(cards), 'expected': len(cards), 'noun': 'cards', 'groups': [{'id': g, 'label': l, 'title': t} for g, l, t in GROUPS], 'cards': cards}
    with open(DATA, 'w') as fh:
        fh.write('// Generated by Tyndale/tools/build-cards.py. Do not edit by hand.\n')
        fh.write('window.SDG_CARDS = ' + json.dumps(data, indent=1) + ';\n')
    print(f'{len(cards)} cards; pictures: ' + ', '.join(n for n, _, _ in PICTURES))

main()
