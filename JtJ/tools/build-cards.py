#!/usr/bin/env python3
"""Build the Journeys through Jerusalem card gallery from the card pictures in assets/jtj/.

  python3 JtJ/tools/build-cards.py            (run from the repo root)

Reads assets/jtj/*v4.png (the 18 character cards) and 'Card Back*.png', writes WebP files at 320, 640 and full size to
assets/jtj-web/cards/ and a list of them to JtJ/cards-data.js, which the page reads. Re-running is safe: files that are
already newer than their source are skipped.
"""
import json, os, re
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'assets', 'jtj')
OUT = os.path.join(ROOT, 'assets', 'jtj-web', 'cards')
DATA = os.path.join(ROOT, 'JtJ', 'cards-data.js')
WIDTHS = (320, 640, 820)
EXPECTED = 18
APOSTLES = ['Peter', 'Andrew', 'James', 'John', 'Philip', 'Matthew', 'Thomas']
FRIENDS = ['Mary Magdalene', 'Nicodemus', 'Joseph of Arimathea', 'Simon of Cyrene', 'Cleopas']
ENEMIES = ['Caiaphas', 'Judas', 'Malchus', 'Centurion', 'Pharisee', 'Scribe']
GROUPS = [('apostle', 'Apostles', 'Apostles (green bar)', APOSTLES), ('friend', 'Friends of Jesus', 'Friends of Jesus (blue bar)', FRIENDS),
          ('enemy', 'Enemies of Christ', 'Enemies of Christ (red bar)', ENEMIES)]
KIND = {'apostle': 'an Apostle', 'friend': 'a Friend of Jesus', 'enemy': 'an Enemy of Christ'}

def main():
    os.makedirs(OUT, exist_ok=True)
    found, back, made = [], None, 0
    for f in sorted(os.listdir(SRC)):
        stem, ext = os.path.splitext(f)
        if ext.lower() != '.png': continue
        path = os.path.join(SRC, f)
        if stem.lower().startswith('card back'): cid, info = 'back', None
        else:
            m = re.match(r'^(.+) v\d+$', stem)
            info = next(((gid, m.group(1), names.index(m.group(1))) for gid, _, _, names in GROUPS if m and m.group(1) in names), None)
            if not info: print('skipped', f); continue
            cid = re.sub(r'[^a-z0-9]+', '-', info[1].lower()).strip('-')
        im = None
        for w in WIDTHS:
            out = os.path.join(OUT, f'{cid}-{w}.webp')
            if os.path.exists(out) and os.path.getmtime(out) >= os.path.getmtime(path): continue
            if im is None: im = Image.open(path).convert('RGBA')
            (im if w >= im.width else im.resize((w, round(w * im.height / im.width)), Image.LANCZOS)).save(out, 'WEBP', quality=82, method=4); made += 1
        w0, h0 = Image.open(path).size
        entry = dict(src=f'../assets/jtj-web/cards/{cid}', widths=list(WIDTHS), w=w0, h=h0)
        if info is None: back = dict(entry, alt='The back of a Journeys through Jerusalem Character Card.')
        else: found.append((info, cid, entry))
    order = {g[0]: i for i, g in enumerate(GROUPS)}
    cards = [dict(id=cid, group=i[0], name=i[1], alt=f'The {i[1]} card ({KIND[i[0]]}).', **e) for i, cid, e in sorted(found, key=lambda x: (order[x[0][0]], x[0][2]))]
    data = dict(total=len(cards), expected=EXPECTED, noun='character cards', countAll=False, groups=[dict(id=i, label=l, title=t) for i, l, t, _ in GROUPS], cards=cards)
    if back: data['back'] = back
    with open(DATA, 'w') as fh:
        fh.write('// Generated by JtJ/tools/build-cards.py from assets/jtj/. Do not edit by hand.\nwindow.SDG_CARDS = ' + json.dumps(data, indent=1, ensure_ascii=False) + ';\n')
    print(f'{len(cards)} cards (expected {EXPECTED}), back: {bool(back)}, {made} images made')

if __name__ == '__main__': main()
