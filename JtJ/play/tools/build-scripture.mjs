// Builds js/scripture-data.js (World English Bible, public domain) with the text of every passage on the 18 Character Cards.
// The Bible text is the per-book JSON of the npm package `world-english-bible` (github.com/TehShrike/world-english-bible).
//   npm pack world-english-bible && mkdir web && tar xzf world-english-bible-*.tgz -C web
//   node tools/build-scripture.mjs web/package/json js/scripture-data.js
import { readFileSync, writeFileSync } from 'node:fs';
import { CARDS } from '../js/cards.js';

const [dir, out] = process.argv.slice(2);
const FILES = { Matthew: 'matthew', Mark: 'mark', Luke: 'luke', John: 'john', Acts: 'acts' };
const books = {};
const book = (name) => (books[name] ??= JSON.parse(readFileSync(`${dir}/${FILES[name]}.json`, 'utf8')));

// "Mark 13:3-37" -> verses [[3, "text"], ...]; a verse split over several elements is joined
function passage(ref) {
  const m = /^(\w+) (\d+):(\d+)(?:-(\d+))?$/.exec(ref);
  if (!m) throw new Error(`cannot read ${ref}`);
  const [, name, ch, from, to] = [m[0], m[1], Number(m[2]), Number(m[3]), Number(m[4] || m[3])];
  const verses = new Map();
  for (const el of book(name)) {
    if (el.chapterNumber !== ch || el.verseNumber < from || el.verseNumber > to) continue;
    if (el.type === 'paragraph text' || el.type === 'line text') verses.set(el.verseNumber, ((verses.get(el.verseNumber) || '') + ' ' + el.value).replace(/\s+/g, ' ').trim());
  }
  for (let v = from; v <= to; v++) if (!verses.get(v)) throw new Error(`no text for ${name} ${ch}:${v}`);
  return [...verses].sort((a, b) => a[0] - b[0]);
}

const passages = {};
for (const c of CARDS) for (const s of c.stops) passages[s.ref] ??= passage(s.ref);
writeFileSync(out, '// Generated by tools/build-scripture.mjs from the World English Bible (public domain). Do not edit by hand.\n' +
  'export default ' + JSON.stringify({ translation: 'World English Bible', passages }) + ';\n');
console.log(`${Object.keys(passages).length} passages, ${Object.values(passages).reduce((n, p) => n + p.length, 0)} verses`);
