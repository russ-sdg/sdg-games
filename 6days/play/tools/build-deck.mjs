// Writes js/deck-data.js from the card gallery list (6days/cards-data.js): the 40 Day cards, each design once.
//   node 6days/play/tools/build-deck.mjs
import fs from 'node:fs';
import vm from 'node:vm';
const here = new URL('.', import.meta.url).pathname;
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(here + '../../cards-data.js', 'utf8'), ctx);
const cards = ctx.window.SDG_CARDS.cards;
const day = cards.filter((c) => /^day\d$/.test(c.group)).map((c) => ({ id: c.id, day: Number(c.group.slice(3)), name: c.name }));
const em = cards.find((c) => c.group === 'evening-morning');
const out = `// Generated by 6days/play/tools/build-deck.mjs from 6days/cards-data.js. Do not edit by hand.
// The 40 Day cards (each design appears once in the box) and the Evening & Morning design (6 copies). Point cards are not
// simulated card by card: a play simply scores its points.
export const DAY_CARDS = ${JSON.stringify(day)};
export const EM_CARD = ${JSON.stringify({ id: em.id, name: 'Evening & Morning' })};
export const EM_COPIES = 6;
`;
fs.writeFileSync(here + '../js/deck-data.js', out);
console.log(day.length, 'day cards');
