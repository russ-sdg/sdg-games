#!/usr/bin/env python3
"""Build the Roman Catacombs card gallery data.

  python3 roman-catacombs/tools/build-cards.py          (run from the repo root)

The 90 card faces are the ones the scorepad's Play mode deals: the list `cardImages` in js/Catacombs.js, with
each face in assets/<name>sm.png. This converts them to WebP (assets/roman-catacombs/cards/), sorts them into
the seven categories in canon order, and writes roman-catacombs/cards-data.js for the product page gallery.
"""
import json, os, re
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUT = os.path.join(ROOT, 'assets', 'roman-catacombs', 'cards')
DATA = os.path.join(ROOT, 'roman-catacombs', 'cards-data.js')

GROUPS = [
    ('pentateuch', 'Pentateuch', 'Genesis to Deuteronomy'),
    ('historical', 'Historical Books', 'Joshua to Esther'),
    ('wisdom', 'Wisdom Books', 'Job to Song of Solomon'),
    ('prophets', 'Prophets', 'Isaiah to Malachi'),
    ('gospels', 'Gospels & Acts', 'Matthew to Acts'),
    ('paul', "Paul's Epistles", 'Romans to Philemon'),
    ('general', 'General Epistles & Revelation', 'Hebrews to Revelation'),
]
BOOKS = [  # canon order: (group, display name)
    *[('pentateuch', b) for b in ['Genesis', 'Exodus', 'Leviticus', 'Numbers', 'Deuteronomy']],
    *[('historical', b) for b in ['Joshua', 'Judges', 'Ruth', '1 Samuel', '2 Samuel', '1 Kings', '2 Kings', '1 Chronicles', '2 Chronicles', 'Ezra', 'Nehemiah', 'Esther']],
    *[('wisdom', b) for b in ['Job', 'Psalms', 'Proverbs', 'Ecclesiastes', 'Song of Solomon']],
    *[('prophets', b) for b in ['Isaiah', 'Jeremiah', 'Lamentations', 'Ezekiel', 'Daniel', 'Hosea', 'Joel', 'Amos', 'Obadiah', 'Jonah', 'Micah', 'Nahum', 'Habakkuk', 'Zephaniah', 'Haggai', 'Zechariah', 'Malachi']],
    *[('gospels', b) for b in ['Matthew', 'Mark', 'Luke', 'John', 'Acts']],
    *[('paul', b) for b in ['Romans', '1 Corinthians', '2 Corinthians', 'Galatians', 'Ephesians', 'Philippians', 'Colossians', '1 Thessalonians', '2 Thessalonians', '1 Timothy', '2 Timothy', 'Titus', 'Philemon']],
    *[('general', b) for b in ['Hebrews', 'James', '1 Peter', '2 Peter', '1 John', '2 John', '3 John', 'Jude', 'Revelation']],
]
TOKEN = {b.replace(' ', '').replace('ofSolomon', ''): (g, b, i) for i, (g, b) in enumerate(BOOKS)}   # 'Song' -> Song of Solomon

def main():
    src = open(os.path.join(ROOT, 'js', 'Catacombs.js'), encoding='utf-8').read()
    names = json.loads(re.search(r'cardImages = (\[.*?\]);', src).group(1))
    os.makedirs(OUT, exist_ok=True)
    cards, wanted = [], set()
    for n in names:
        m = re.fullmatch(r'(.+?)(\d+)v\d+', n)
        g, book, order = TOKEN[m.group(1)]
        out = f'{n}-250.webp'      # the gallery script looks for <id>-<width>.webp
        wanted.add(out)
        path = os.path.join(ROOT, 'assets', f'{n}sm.png')
        dst = os.path.join(OUT, out)
        if not os.path.exists(dst) or os.path.getmtime(dst) < os.path.getmtime(path):
            Image.open(path).convert('RGBA').save(dst, quality=90, method=6)       # keep the rounded, transparent corners
        w, h = Image.open(dst).size
        assert w == 250, (n, w)
        cards.append({'id': n, 'group': g, 'name': book, 'order': order, 'src': f'../assets/roman-catacombs/cards/{n}', 'widths': [w], 'w': w, 'h': h})
    cards.sort(key=lambda c: (c['order'], c['id']))
    for c in cards:
        del c['order']
    back = Image.open(os.path.join(ROOT, 'assets', 'RCBackv2.png')).convert('RGBA')
    back.thumbnail((600, 818))
    back.save(os.path.join(OUT, f'back-{back.width}.webp'), quality=86, method=6)
    wanted.add(f'back-{back.width}.webp')
    for f in os.listdir(OUT):
        if f.endswith('.webp') and f not in wanted:
            os.remove(os.path.join(OUT, f))
    data = {'total': len(cards), 'expected': 90, 'noun': 'cards',
            'back': {'src': '../assets/roman-catacombs/cards/back', 'widths': [back.width], 'w': back.width, 'h': back.height},
            'groups': [{'id': g, 'label': l, 'title': t} for g, l, t in GROUPS], 'cards': cards}
    with open(DATA, 'w') as fh:
        fh.write('// Generated by roman-catacombs/tools/build-cards.py. Do not edit by hand.\n')
        fh.write('window.SDG_CARDS = ' + json.dumps(data, indent=1) + ';\n')
    per = {g: sum(c['group'] == g for c in cards) for g, _, _ in GROUPS}
    print(f'{len(cards)} cards:', ', '.join(f'{g} {n}' for g, n in per.items()))

main()
