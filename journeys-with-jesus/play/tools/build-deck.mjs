// Makes js/deck-data.js from the gallery's list of cards (../cards-data.js), so the game's deck is the printed deck:
// the same pictures, and the same number of copies of each. Run again after rebuilding the gallery:
//   node journeys-with-jesus/play/tools/build-deck.mjs
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { PLACES } from '../js/board-data.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(here, '../../cards-data.js'), 'utf8'), ctx);
const data = JSON.parse(JSON.stringify(ctx.window.SDG_CARDS));

// The points printed on each Journey Card (read off the cards: the corners).
const POINTS = {
  'caesarea-philippi-to-bethsaida': 9, 'capernaum-to-bethsaida': 4, 'capernaum-to-gadara': 4, 'capernaum-to-nain': 25, 'capernaum-to-nazareth': 16,
  'jericho-to-jerusalem': 9, 'jerusalem-to-bethany': 4, 'jerusalem-to-bethlehem': 4, 'mount-hermon-to-caesarea-philippi': 4,
  'nazareth-to-bethany-beyond-jordan': 25, 'nazareth-to-jerusalem': 25, 'tyre-to-gadara': 16, 'tyre-to-gennesaret': 25,
  'bethany-beyond-jordan-to-bethany': 9, 'bethany-beyond-jordan-to-jerusalem': 16, 'cana-to-bethany-beyond-jordan': 16, 'cana-to-sychar': 16,
  'capernaum-to-cana': 9, 'capernaum-to-jerusalem': 36, 'countryside-to-jerusalem': 16, 'ephraim-to-bethany': 9, 'gennesaret-to-jerusalem': 36,
  'sychar-to-countryside': 4,
};
const byName = Object.fromEntries(Object.entries(PLACES).map(([id, p]) => [p.name, id]));
const REGION_WILD = { Galilee: 'galilee', Decapolis: 'decapolis', Judea: 'judea', Perea: 'perea', Samaria: 'samaria', Syria: 'syria', 'Israel National': 'israel' };
const img = (c) => c.src.split('/').pop();

const places = [], wilds = [], journeys = [];
for (const c of data.cards) {
  const exp = c.group === 'expansion';
  if (c.group === 'backs' || c.group === 'tokens') continue;
  if (c.name.includes(' to ')) {
    const [a, b] = c.name.split(' to ').map((n) => byName[n]);
    if (!a || !b) throw new Error('unknown place in ' + c.name);
    if (!(c.id in POINTS)) throw new Error('no points for ' + c.id);
    journeys.push({ id: c.id, a, b, points: POINTS[c.id], exp });
    continue;
  }
  const w = c.name.match(/^(.*) Wild Card/);
  if (w) { wilds.push({ id: c.id, img: img(c), region: REGION_WILD[w[1]], copies: c.copies, exp }); continue; }
  const name = c.name.replace(/ \(\d+ of \d+\)$/, '');
  if (!byName[name]) throw new Error('unknown place ' + c.name);
  places.push({ id: c.id, img: img(c), place: byName[name], copies: c.copies, exp });
}

const out = `// Journeys with Jesus: the printed deck. Generated by tools/build-deck.mjs from ../cards-data.js. Do not edit by hand.
// A card's \`img\` is its picture in assets/jwj/cards (the same picture can be both a base card and an expansion card:
// the expansion adds more copies). \`exp\` marks the cards that come only in the Gospel of John Expansion Pack.
export const PLACE_CARDS = ${JSON.stringify(places)};
export const WILD_CARDS = ${JSON.stringify(wilds)};
export const JOURNEY_CARDS = ${JSON.stringify(journeys)};
`;
fs.writeFileSync(path.join(here, '../js/deck-data.js'), out);
const sum = (l, f) => l.reduce((n, c) => n + (f(c) ? c.copies ?? 1 : 0), 0);
console.log('place', sum(places, (c) => !c.exp), '+', sum(places, (c) => c.exp), ' wild', sum(wilds, (c) => !c.exp), '+', sum(wilds, (c) => c.exp),
  ' journeys', journeys.filter((j) => !j.exp).length, '+', journeys.filter((j) => j.exp).length);
