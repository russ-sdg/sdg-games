#!/usr/bin/env python3
"""Build the Roman Road card gallery from the card pictures in assets/roman-road/.

  python3 RomanRoad/tools/build-cards.py            (run from the repo root)

Reads assets/roman-road/Rom-<chapter>-<verse>-<n>V<version>.png (the 32 card faces: 4 verses x 8 cards), writes WebP files
at 320, 640 and full size to assets/rr-web/cards/ and a list of them to RomanRoad/cards-data.js, which the page reads.
Each face is printed once in each of the four decks, so each is listed with copies=4 (128 cards). Re-running is safe: files
that are already newer than their source are skipped.
"""
import json, os, re
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'assets', 'roman-road')
OUT = os.path.join(ROOT, 'assets', 'rr-web', 'cards')
DATA = os.path.join(ROOT, 'RomanRoad', 'cards-data.js')
WIDTHS = (320, 640, 745)
EXPECTED, DECKS = 128, 4
VERSES = [('rom-3-23', 'Romans 3:23', 'Red, apple'), ('rom-6-23', 'Romans 6:23', 'Orange, arrows'), ('rom-5-8', 'Romans 5:8', 'Blue, cross'), ('rom-10-13', 'Romans 10:13', 'Green, life ring')]

def main():
    os.makedirs(OUT, exist_ok=True)
    found, made = [], 0
    for f in sorted(os.listdir(SRC)):
        m = re.match(r'^Rom-(\d+)-(\d+)-(\d+)V\d+\.png$', f)
        if not m: continue
        gid = f'rom-{m.group(1)}-{m.group(2)}'
        order = next((i for i, v in enumerate(VERSES) if v[0] == gid), None)
        if order is None: print('skipped', f); continue
        n, path, cid = int(m.group(3)), os.path.join(SRC, f), f'{gid}-{m.group(3)}'
        im = None
        for w in WIDTHS:
            out = os.path.join(OUT, f'{cid}-{w}.webp')
            if os.path.exists(out) and os.path.getmtime(out) >= os.path.getmtime(path): continue
            if im is None: im = Image.open(path).convert('RGBA')
            (im if w >= im.width else im.resize((w, round(w * im.height / im.width)), Image.LANCZOS)).save(out, 'WEBP', quality=84, method=4); made += 1
        w0, h0 = Image.open(path).size
        v = VERSES[order]
        found.append((order, n, dict(id=cid, group=gid, name=f'{v[1]}, card {n} of 8', alt=f'Roman Road card {n} of 8 from {v[1]} ({v[2].lower()}).', copies=DECKS,
                                     src=f'../assets/rr-web/cards/{cid}', widths=list(WIDTHS), w=w0, h=h0)))
    cards = [c for _, _, c in sorted(found, key=lambda x: x[:2])]
    total = sum(c['copies'] for c in cards)
    data = dict(total=total, expected=EXPECTED, noun='cards', countAll=False, groups=[dict(id=g, label=l, title=f'{l} ({c.lower()})') for g, l, c in VERSES], cards=cards)
    with open(DATA, 'w') as fh:
        fh.write('// Generated by RomanRoad/tools/build-cards.py from assets/roman-road/. Do not edit by hand.\nwindow.SDG_CARDS = ' + json.dumps(data, indent=1, ensure_ascii=False) + ';\n')
    print(f'{len(cards)} faces = {total} cards (expected {EXPECTED}), {made} images made')

if __name__ == '__main__': main()
