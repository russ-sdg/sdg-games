#!/usr/bin/env python3
"""Build the Prophets & Kings card gallery from the card pictures in assets/pk/.

  python3 pk/tools/build-cards.py            (run from the repo root)

Reads assets/pk/*.png (the card faces and the card back; any other file there is ignored), writes WebP files at 320, 640
and full size to assets/pk-web/cards/ and a list of them to pk/cards-data.js, which the page reads. The deck has 70 cards
but 67 pictures: Jeroboam II is printed 3 times and Darius twice from one picture each (the page's summary table says how many
cards each king and prophet has). Re-running is safe: files that are already newer than their source are skipped.
"""
import json, os, re
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'assets', 'pk')
OUT = os.path.join(ROOT, 'assets', 'pk-web', 'cards')
DATA = os.path.join(ROOT, 'pk', 'cards-data.js')
WIDTHS = (320, 640, 825)
EXPECTED = 70
PROPHETS = ['Elijah', 'Elisha', 'Jonah', 'Amos', 'Hosea', 'Isaiah', 'Micah', 'Zephaniah', 'Jeremiah', 'Habakkuk', 'Daniel', 'Ezekiel', 'Zechariah', 'Haggai']
ISRAEL = ['Ahab', 'Ahaziah', 'Joram', 'Jehu', 'Jehoahaz (Israel)', 'Jehoash', 'Jeroboam II']
JUDAH = ['Uzziah', 'Jotham', 'Ahaz', 'Hezekiah', 'Manasseh', 'Josiah', 'Jehoahaz (Judah)', 'Jehoiakim', 'Jehoiachin', 'Zedekiah']
GENTILE = ['Nebuchadnezzar', 'Belshazzar', 'Cyrus', 'Darius']
GROUPS = [('prophets', 'Prophets', 'The prophets (red names)', PROPHETS), ('israel', 'Kings of Israel', 'Kings of the northern kingdom (blue names)', ISRAEL),
          ('judah', 'Kings of Judah', 'Kings of the southern kingdom (green names)', JUDAH), ('gentile', 'Foreign kings', 'Kings of other nations (purple names)', GENTILE)]
FILE_NAMES = {'Jehoahaz': 'Jehoahaz (Israel)', 'JehoahazJudah': 'Jehoahaz (Judah)', 'Jehoikim': 'Jehoiakim', 'Jeroboam': 'Jeroboam II'}   # file name -> the name on the card
COPIES = {'Jeroboam II': 3, 'Darius': 2}              # printed more than once from the one picture
KIND = {'prophets': 'prophet', 'israel': 'king of Israel', 'judah': 'king of Judah', 'gentile': 'foreign king'}

def parse(stem):
    m = re.match(r'^([A-Za-z]+?)(\d*)V\d+$', stem)
    if not m: return None
    base, n = m.group(1), m.group(2)
    name = FILE_NAMES.get(base, base)
    for gid, _, _, names in GROUPS:
        if name in names: return gid, name, int(n) if n else 1, names.index(name)
    return None

def main():
    os.makedirs(OUT, exist_ok=True)
    found, back, made = [], None, 0
    for f in sorted(os.listdir(SRC)):
        stem, ext = os.path.splitext(f)
        if ext.lower() != '.png': continue
        path = os.path.join(SRC, f)
        if 'back' in stem.lower(): cid, info = 'back', None
        else:
            info = parse(stem)
            if not info: print('skipped', f); continue
            cid = re.sub(r'[^a-z0-9]+', '-', f'{info[1]}-{info[2]}'.lower()).strip('-')
        im = None
        for w in WIDTHS:
            out = os.path.join(OUT, f'{cid}-{w}.webp')
            if os.path.exists(out) and os.path.getmtime(out) >= os.path.getmtime(path): continue
            if im is None: im = Image.open(path).convert('RGBA')
            (im if w >= im.width else im.resize((w, round(w * im.height / im.width)), Image.LANCZOS)).save(out, 'WEBP', quality=82, method=4); made += 1
        w0, h0 = Image.open(path).size
        entry = dict(src=f'../assets/pk-web/cards/{cid}', widths=list(WIDTHS), w=w0, h=h0)
        if info is None: back = dict(entry, alt='The back of a Prophets & Kings card.')
        else: found.append((info, cid, entry))
    count = {}
    for info, _, _ in found: count[info[1]] = count.get(info[1], 0) + 1
    order = {g[0]: i for i, g in enumerate(GROUPS)}
    cards = []
    for info, cid, entry in sorted(found, key=lambda x: (order[x[0][0]], x[0][3], x[0][2])):
        gid, name, n, _ = info
        label = f'{name} ({n} of {count[name]})' if count[name] > 1 else name
        c = dict(id=cid, group=gid, name=label, alt=f'The {name} card ({KIND[gid]}).' + (f' Card {n} of {count[name]} for this {"prophet" if gid == "prophets" else "king"}.' if count[name] > 1 else ''), **entry)
        if name in COPIES: c['copies'] = COPIES[name]
        cards.append(c)
    total = sum(c.get('copies', 1) for c in cards)
    data = dict(total=total, expected=EXPECTED, noun='cards', countAll=False, groups=[dict(id=i, label=l, title=t) for i, l, t, _ in GROUPS], cards=cards)
    if back: data['back'] = back
    with open(DATA, 'w') as fh:
        fh.write('// Generated by pk/tools/build-cards.py from assets/pk/. Do not edit by hand.\nwindow.SDG_CARDS = ' + json.dumps(data, indent=1, ensure_ascii=False) + ';\n')
    print(f'{len(cards)} pictures = {total} cards (expected {EXPECTED}), back: {bool(back)}, {made} images made')

if __name__ == '__main__': main()
