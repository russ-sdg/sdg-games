// Builds js/scripture-data.js (World English Bible, public domain) from the per-book JSON
// in https://github.com/TehShrike/world-english-bible (json/<book>.json).
// usage: node build-scripture.mjs <dir with acts.json, revelation.json, ...> <out js file>
import { readFileSync, writeFileSync } from 'node:fs';

const [dir, out] = process.argv.slice(2);
const FILES = { Acts: 'acts', Revelation: 'revelation', Philippians: 'philippians', '1 Thessalonians': '1thessalonians',
  Colossians: 'colossians', Titus: 'titus', Romans: 'romans', '1 Peter': '1peter' };

// city id -> [book, chapter, firstVerse, lastVerse]
const CITY_PASSAGES = {
  Philippi: ['Philippians', 1, 6, 6],
  Neapolis: ['Acts', 16, 11, 11],
  Thessalonica: ['1 Thessalonians', 1, 3, 3],
  Berea: ['Acts', 17, 11, 11],
  Athens: ['Acts', 17, 22, 23],
  Corinth: ['Acts', 18, 9, 10],
  Troas: ['Acts', 16, 9, 9],
  Pergamum: ['Revelation', 2, 13, 13],
  Smyrna: ['Revelation', 2, 10, 10],
  Miletus: ['Acts', 20, 32, 32],
  Cridus: ['Acts', 27, 7, 7],           // Cnidus
  Thyatira: ['Acts', 16, 14, 14],
  Sardis: ['Revelation', 3, 2, 2],
  Philadelphia: ['Revelation', 3, 8, 8],
  Laodicea: ['Revelation', 3, 20, 20],
  Ephesus: ['Acts', 19, 20, 20],
  Cyprus: ['Acts', 13, 4, 4],
  Rhodes: ['Acts', 21, 1, 1],
  Patmos: ['Revelation', 1, 9, 9],
  Crete: ['Titus', 1, 5, 5],
  Antioch: ['Acts', 11, 26, 26],
  Iconium: ['Acts', 14, 1, 1],
  Lystra: ['Acts', 14, 15, 15],
  Derbe: ['Acts', 14, 21, 21],
  Perga: ['Acts', 13, 13, 13],
  Colossae: ['Colossians', 1, 4, 4],
};
// cities with no passage here are not named in the New Testament; they get one of these
const FALLBACK = [['Romans', 10, 15, 15], ['Acts', 1, 8, 8], ['Romans', 1, 16, 16]];
const CALLED = ['1 Peter', 5, 2, 2];

const books = {};
const book = (name) => (books[name] ??= JSON.parse(readFileSync(`${dir}/${FILES[name]}.json`, 'utf8')));

function passage([name, ch, from, to]) {
  const parts = [];
  for (const el of book(name)) {
    if (el.chapterNumber !== ch || el.verseNumber < from || el.verseNumber > to) continue;
    if (el.type === 'paragraph text' || el.type === 'line text') parts.push(el.value);
  }
  // a snippet cut mid-sentence ends in an ellipsis rather than a dangling , ; or :
  const text = parts.join(' ').replace(/\s+/g, ' ').trim().replace(/[,;:]$/, '\u2026');
  if (!text) throw new Error(`no text for ${name} ${ch}:${from}-${to}`);
  return { ref: `${name} ${ch}:${from}${to > from ? '–' + to : ''}`, text };
}

const data = {
  translation: 'World English Bible',   // public domain
  cities: Object.fromEntries(Object.entries(CITY_PASSAGES).map(([id, p]) => [id, passage(p)])),
  fallback: FALLBACK.map(passage),
  called: passage(CALLED),
};
writeFileSync(out, '// Generated by tools/build-scripture.mjs from the World English Bible. Do not edit by hand.\n' +
  'export default ' + JSON.stringify(data, null, 1) + ';\n');
console.log(`${Object.keys(data.cities).length} city passages, ${data.fallback.length} fallbacks`);
