#!/usr/bin/env python3
"""Build the Three-by-Three card gallery from the card pictures in assets/ (3x3<Tribe>.webp).

  python3 3x3/tools/build-cards.py            (run from the repo root)

Writes WebP files at 320, 640 and full size to assets/3x3-web/cards/ and a list of them to 3x3/cards-data.js, which the page
reads. The deck is 3 of each of the 13 tribes (39) plus 3 information cards (42); each tribe is listed once with copies=3.
The Tribal Allotments picture (3x3Israel) is the back of the three information cards, so it is listed with copies=0.
Re-running is safe: files that are already newer than their source are skipped.
"""
import json, os
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'assets')
OUT = os.path.join(ROOT, 'assets', '3x3-web', 'cards')
DATA = os.path.join(ROOT, '3x3', 'cards-data.js')
WIDTHS = (320, 640, 745)
EXPECTED = 42
TRIBES = ['Judah', 'Issachar', 'Zebulun', 'Reuben', 'Simeon', 'Gad', 'Levi', 'Ephraim', 'Manasseh', 'Benjamin', 'Dan', 'Asher', 'Naphtali']   # the order of march: the number on the card
INFO = [('JacobsSons', "Jacob's sons", "The Jacob's Sons information card: the twelve sons of Jacob in birth order with their mothers, and the two sons of Joseph.", 1),
        ('Numbers1', 'Census (Numbers 1)', 'The Numbers 1 census information card: the tribes and their census numbers.', 1),
        ('Numbers26', 'Census (Numbers 26)', 'The Numbers 26 census information card: the tribes and their census numbers.', 1),
        ('Israel', 'Information card back', 'The back of the information cards: the territories in the Promised Land allotted to the twelve tribes.', 0)]
BACK_ALT = 'The back of a Tribe card: the twelve tribes camped around the Tabernacle in the wilderness.'

def make(name):
    path, made = os.path.join(SRC, f'3x3{name}.webp'), 0
    cid, im = name.lower(), None
    for w in WIDTHS:
        out = os.path.join(OUT, f'{cid}-{w}.webp')
        if os.path.exists(out) and os.path.getmtime(out) >= os.path.getmtime(path): continue
        if im is None: im = Image.open(path).convert('RGBA')
        (im if w >= im.width else im.resize((w, round(w * im.height / im.width)), Image.LANCZOS)).save(out, 'WEBP', quality=84, method=4); made += 1
    w0, h0 = Image.open(path).size
    return cid, dict(src=f'../assets/3x3-web/cards/{cid}', widths=list(WIDTHS), w=w0, h=h0), made

def main():
    os.makedirs(OUT, exist_ok=True)
    cards, made = [], 0
    for i, t in enumerate(TRIBES, 1):
        cid, e, m = make(t); made += m
        label = 'Levi (both parts of the tribe)' if t == 'Levi' else t
        cards.append(dict(id=cid, group='tribes', name=f'{i}. {t}', alt=f'The {t} card, number {i}: a map of the territory allotted to the tribe.' if t != 'Levi' else 'The Levi card, number 7: the breastplate of judgement with the twelve stones.', copies=3, **e))
    for n, name, alt, copies in INFO:
        cid, e, m = make(n); made += m
        cards.append(dict(id=cid, group='info', name=name, alt=alt, copies=copies, **e))
    cid, e, m = make('Back'); made += m
    total = sum(c['copies'] for c in cards)
    data = dict(total=total, expected=EXPECTED, noun='cards', countAll=False,
                groups=[dict(id='tribes', label='Tribe cards', title='The 13 tribes, numbered in the order they set out'), dict(id='info', label='Information cards', title='The three information cards and their back')],
                cards=cards, back=dict(e, alt=BACK_ALT))
    with open(DATA, 'w') as fh:
        fh.write('// Generated by 3x3/tools/build-cards.py from assets/3x3*.webp. Do not edit by hand.\nwindow.SDG_CARDS = ' + json.dumps(data, indent=1, ensure_ascii=False) + ';\n')
    print(f'{len(cards)} pictures = {total} cards (expected {EXPECTED}), {made} images made')

if __name__ == '__main__': main()
