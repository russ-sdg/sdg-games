#!/usr/bin/env python3
"""Build the Illuminate card gallery from the card pictures in assets/Illuminate/.

  python3 illuminate/tools/build-cards.py            (run from the repo root)

Reads assets/Illuminate/*.png (the 48 Gospel cards, the 4 Role Cards and the card back; any other file there is ignored),
writes WebP files at 320, 640 and full size to assets/illuminate-web/cards/ and a list of them to illuminate/cards-data.js,
which the page reads. Re-running is safe: files that are already newer than their source are skipped.
"""
import json, os, re
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'assets', 'Illuminate')
OUT = os.path.join(ROOT, 'assets', 'illuminate-web', 'cards')
DATA = os.path.join(ROOT, 'illuminate', 'cards-data.js')
WIDTHS = (320, 640, 825)
EXPECTED = 52            # 4 suits of 12 + 4 Role Cards
SUITS = ['Matthew', 'Mark', 'Luke', 'John']
ROLES = ['Doctor', 'Neighbor', 'Preacher', 'Teacher']
SPECIAL = {'Matthew 19:30': 'The lowest card (any Gospel) wins this trick.', 'John 1:5': 'Grace cards are disabled for this trick.',
           'Mark 14:27': 'The player who led wins this trick.', 'Luke 19:24': 'Rotate roles to the right.'}
GROUPS = [('matthew', 'Matthew', 'The Gospel of Matthew'), ('mark', 'Mark', 'The Gospel of Mark'), ('luke', 'Luke', 'The Gospel of Luke'),
          ('john', 'John', 'The Gospel of John'), ('roles', 'Role Cards', 'Doctor, Neighbor, Preacher and Teacher')]

def parse(stem):
    m = re.match(r'^(Matthew|Mark|Luke|John)[ -](\d+)-(\d+)(?:-(\d+))?-V\d+$', stem)
    if m:
        suit, ch, v1, v2 = m.groups()
        ref = f'{suit} {ch}:{v1}' + (f'-{v2}' if v2 else '')
        key = f'{suit} {ch}:{v1}'
        alt = f'The {suit} card for {ref}.'
        if key in SPECIAL: alt += f' A Special Action card: {SPECIAL[key]}'
        name = ref + (' ★ Special Action' if key in SPECIAL else '')
        return dict(id=f'{suit.lower()}-{ch}-{v1}' + (f'-{v2}' if v2 else ''), group=suit.lower(), name=name, alt=alt, sort=(int(ch), int(v1)))
    m = re.match(r'^(Doctor|Neighbor|Preacher|Teacher)-Card-V\d+$', stem)
    if m:
        r = m.group(1)
        return dict(id=r.lower(), group='roles', name=f'{r} Role Card', alt=f'The {r} Role Card.', sort=(ROLES.index(r), 0))
    return None

def save(im, out):
    if os.path.exists(out): return 0
    im.save(out, 'WEBP', quality=84, method=6); return 1

def main():
    os.makedirs(OUT, exist_ok=True)
    cards, made, back = [], 0, None
    for f in sorted(os.listdir(SRC)):
        stem, ext = os.path.splitext(f)
        if ext.lower() != '.png': continue
        path = os.path.join(SRC, f)
        info = parse(stem)
        if stem.startswith('Card-Back'): cid = 'back'
        elif info: cid = info['id']
        else: continue
        im = Image.open(path).convert('RGBA')
        for w in WIDTHS:
            out = os.path.join(OUT, f'{cid}-{w}.webp')
            if os.path.exists(out) and os.path.getmtime(out) >= os.path.getmtime(path): continue
            made += save(im if w >= im.width else im.resize((w, round(w * im.height / im.width)), Image.LANCZOS), out) if os.path.exists(out) is False else 0
        entry = dict(src=f'../assets/illuminate-web/cards/{cid}', widths=list(WIDTHS), w=im.width, h=im.height)
        if cid == 'back': back = dict(entry, alt='The back of an Illuminate card: parchment with a Book of Kells design.')
        else: cards.append(dict(info, **entry))
    order = {g[0]: i for i, g in enumerate(GROUPS)}
    cards.sort(key=lambda c: (order[c['group']], c['sort']))
    for c in cards: del c['sort']
    data = dict(total=len(cards), expected=EXPECTED, noun='cards', countAll=False, groups=[dict(id=i, label=l, title=t) for i, l, t in GROUPS], cards=cards)
    if back: data['back'] = back
    with open(DATA, 'w') as fh:
        fh.write('// Generated by illuminate/tools/build-cards.py from assets/Illuminate/. Do not edit by hand.\nwindow.SDG_CARDS = ' + json.dumps(data, indent=1, ensure_ascii=False) + ';\n')
    print(f'{len(cards)} cards (expected {EXPECTED}), back: {bool(back)}, {made} images made')

if __name__ == '__main__': main()
